LR13_DEV = {"kb02", "kb05", "kb06", "kb12", "gen02", "gen07"}


def main():
    docs = {json.loads(l)["doc_id"]: json.loads(l) for l in open(DOCS, encoding="utf-8")}
    assert len(SENTENCES) == 50, len(SENTENCES)
    rows = []
    for i, (d, s) in enumerate(SENTENCES, 1):
        off = docs[d]["text"].find(s)
        assert off >= 0, f"речення не знайдено дослівно: {d}: {s[:60]}"
        group = "article" if d.startswith(("kb", "prj")) else "register"
        rows.append({"id": f"s{i:02d}", "doc_id": d, "offset": off, "group": group,
                     "lr13_dev_doc": int(d in LR13_DEV), "sensitivity": docs[d]["sensitivity"], "text": s})
    with open(ROOT / "data/sentences.csv", "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), delimiter=";")
        w.writeheader(); w.writerows(rows)
    gold = ROOT / "data/gold.csv"
    if not gold.exists():
        with open(gold, "w", newline="", encoding="utf-8-sig") as f:
            w = csv.writer(f, delimiter=";")
            w.writerow(["id", "text", "triples", "note"])
            for r in rows:
                w.writerow([r["id"], r["text"], "", ""])
        print("створено порожній шаблон data/gold.csv — розмітьте стовпчик triples за docs/annotation_guide.md")
    print(f"речень: {len(rows)}; статті: {sum(r['group'] == 'article' for r in rows)}; "
          f"реєстри: {sum(r['group'] == 'register' for r in rows)}; з dev-документів ЛР13: {sum(r['lr13_dev_doc'] for r in rows)}")


if __name__ == "__main__":
    main()
