def main():
    docs = {}
    for line in open(LAB11 / "data" / "clean" / "docs.jsonl", encoding="utf-8"):
        d = json.loads(line)
        docs[d["doc_id"]] = normalize(" ".join(s["text"] for s in d["sections"]))
    rows, bad = [], []
    for item in Q:
        qid, cat, q, exp, ev, keys = item[:6]
        forbidden = item[6] if len(item) > 6 else []
        extra = item[7] if len(item) > 7 else None
        for d, e in ev:
            if normalize(e) not in docs[d]:
                bad.append((qid, d, e[:50]))
        r = {"id": qid, "category": cat, "question": q, "expected": exp, "role": "analyst",
             "evidences": [{"doc_id": d, "evidence": e, "grade": 2} for d, e in ev], "must_contain": keys, "forbidden": forbidden}
        if extra:
            r["extra_source"] = extra
        rows.append(r)
    if bad:
        sys.exit(f"доказ не знайдено: {bad}")
    (ROOT / "eval").mkdir(exist_ok=True)
    with open(ROOT / "eval" / "sr11_queries.jsonl", "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    from collections import Counter
    print(len(rows), dict(Counter(r["category"] for r in rows)))


if __name__ == "__main__":
    main()
